#!/usr/bin/env node
// Generates the key catalog from the assessment's HidKeyCodes.md reference
// table. Runs once at authoring time — not part of the build, not part of the
// runtime — and its three outputs are committed:
//
//   keys.json                 language-neutral, and what the drift tests read
//   src/catalog.generated.ts  typed module the serverless API and web client import
//   CatalogSeed.g.cs          C# constants the EF Core model seeds from
//
// The .NET side does not read any of these at runtime. CatalogSeed.g.cs feeds
// EF Core's HasData, which bakes the rows into a migration that is then
// committed and frozen — so the database, not a file, is the runtime source of
// truth for which keys exist.
//
//   npm run catalog:generate
//
// Drift tests assert these outputs still match HidKeyCodes.md and each other.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const sourceDoc = join(here, "..", "..", "HidKeyCodes.md");
const outFile = join(here, "keys.json");
const outModule = join(here, "src", "catalog.generated.ts");
const outCsharp = join(here, "..", "..", "apps", "api-dotnet", "Apex.KeyMapping.Api", "Data", "CatalogSeed.g.cs");

const markdown = readFileSync(sourceDoc, "utf8");

// The doc is a series of `## Category` headings, each followed by a markdown
// table whose first column is the key name and second is the hex HID code.
const ROW = /^\|\s*([^|]+?)\s*\|\s*(0x[0-9A-Fa-f]{2})\s*\|\s*(\d+)\s*\|/;

const keys = [];
let category = null;

for (const line of markdown.split("\n")) {
  const heading = /^##\s+(.+?)\s*$/.exec(line);
  if (heading) {
    category = heading[1];
    continue;
  }

  const row = ROW.exec(line.trim());
  if (!row || !category) continue;

  const [, rawName, hex, dec] = row;
  const hidCode = Number.parseInt(hex, 16);

  if (hidCode !== Number.parseInt(dec, 10)) {
    throw new Error(`${rawName}: hex ${hex} and decimal ${dec} disagree in HidKeyCodes.md`);
  }
  if (hidCode < 0x00 || hidCode > 0xff) {
    throw new Error(`${rawName}: HID code ${hex} is outside the 8-bit range`);
  }

  keys.push({
    hidCode,
    hidCodeHex: `0x${hidCode.toString(16).toUpperCase().padStart(2, "0")}`,
    name: rawName.replace(/\s*\(Win\/Cmd\)\s*/, " (Win/Cmd)").trim(),
    category: normalizeCategory(category),
  });
}

function normalizeCategory(raw) {
  // "Numbers (Top Row)" -> "Numbers", "Special / Editing Keys" -> "Special"
  if (raw.startsWith("Numbers")) return "Numbers";
  if (raw.startsWith("Special")) return "Special";
  if (raw.startsWith("Function")) return "Function";
  if (raw.startsWith("Arrow")) return "Arrows";
  if (raw.startsWith("Modifier")) return "Modifiers";
  return raw;
}

if (keys.length === 0) {
  throw new Error("Parsed no keys from HidKeyCodes.md — did the table format change?");
}

const seen = new Map();
for (const key of keys) {
  if (seen.has(key.hidCode)) {
    throw new Error(`Duplicate HID code ${key.hidCodeHex}: ${seen.get(key.hidCode)} and ${key.name}`);
  }
  seen.set(key.hidCode, key.name);
}

keys.sort((a, b) => a.hidCode - b.hidCode);

const catalog = {
  $generatedFrom: "HidKeyCodes.md",
  $generator: "packages/hid-catalog/generate.mjs",
  keyboards: [
    {
      // Slug is what callers put in the URL; name is the human label the
      // assessment specifies ("Apex Pro Gen 3").
      slug: "apex-pro-gen-3",
      name: "Apex Pro Gen 3",
      vendor: "SteelSeries",
      keys,
    },
  ],
};

writeFileSync(outFile, `${JSON.stringify(catalog, null, 2)}\n`);

// Also emit the catalog as a TypeScript module. Importing a .ts module rather
// than the .json keeps behaviour identical across tsc, esbuild, vite and
// vitest, none of which agree on JSON import attributes and asset copying.
// `catalog.drift.test.ts` asserts this module and keys.json stay in step.
writeFileSync(
  outModule,
  [
    "// GENERATED FILE — do not edit by hand.",
    "// Source: HidKeyCodes.md via packages/hid-catalog/generate.mjs",
    '// Regenerate with: npm run catalog:generate',
    "",
    'import type { Catalog } from "./types.js";',
    "",
    `export const generatedCatalog: Catalog = ${JSON.stringify({ keyboards: catalog.keyboards }, null, 2)} as const;`,
    "",
  ].join("\n"),
);

// Also emit the catalog as C# constants. The EF Core model feeds these to
// HasData, which snapshots them into a migration — so this file shapes the
// migration at authoring time and is never read at runtime. Extending the
// catalog therefore means regenerating here *and* adding a new migration;
// editing a committed one would desync databases that already applied it.
const csharpString = (value) => `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
const pad = Math.max(...keys.map((k) => csharpString(k.name).length));

writeFileSync(
  outCsharp,
  [
    "// <auto-generated />",
    "// GENERATED FILE — do not edit by hand.",
    "// Source: HidKeyCodes.md via packages/hid-catalog/generate.mjs",
    "// Regenerate with: npm run catalog:generate",
    "",
    "namespace Apex.KeyMapping.Api.Data;",
    "",
    "/// <summary>",
    "/// The product catalog as shipped: which keys an Apex Pro Gen 3 exposes for",
    "/// remapping. Consumed by <c>ApexDbContext.OnModelCreating</c> via EF Core's",
    "/// <c>HasData</c>, which bakes these rows into a migration. Nothing reads this",
    "/// at runtime — the database is the source of truth once migrated.",
    "/// </summary>",
    "public static class CatalogSeed",
    "{",
    `    public const int KeyboardModelId = 1;`,
    `    public const string Slug = ${csharpString(catalog.keyboards[0].slug)};`,
    `    public const string Name = ${csharpString(catalog.keyboards[0].name)};`,
    `    public const string Vendor = ${csharpString(catalog.keyboards[0].vendor)};`,
    "",
    `    /// <summary>All ${keys.length} keys, in ascending HID code order.</summary>`,
    "    public static readonly (int HidCode, string Name, string Category)[] Keys =",
    "    [",
    ...keys.map(
      (k) =>
        `        (0x${k.hidCode.toString(16).toUpperCase().padStart(2, "0")}, ` +
        `${`${csharpString(k.name)},`.padEnd(pad + 1)} ${csharpString(k.category)}),`,
    ),
    "    ];",
    "}",
    "",
  ].join("\n"),
);

const byCategory = keys.reduce((acc, k) => ({ ...acc, [k.category]: (acc[k.category] ?? 0) + 1 }), {});
console.log(`Wrote ${keys.length} keys to:\n  ${outFile}\n  ${outModule}\n  ${outCsharp}`);
console.table(byCategory);
